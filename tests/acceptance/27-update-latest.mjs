test("a release without the expected asset, and an asset that cannot be downloaded, both fail cleanly", async () => {
  const vault = await cloneVault("rpgvault-latest27-noasset-")
  const before = await snapshot(vault)
  const noAsset = await releaseHost({ release: { tag_name: "v1.1.0", assets: [{ name: "notes.txt", browser_download_url: "http://127.0.0.1:1/download/notes.txt" }] } })
  const first = await cli(vault, ["update", "--latest"], { RPGVAULT_RELEASE_API: noAsset.base })
  assert.notEqual(first.code, 0, `a release without the asset fails; stdout: ${first.stdout}`)
  assert.ok(first.stderr.includes("RPGVault.zip"), `the failure names the expected asset: ${first.stderr}`)
  await noAsset.close()
  const gone = await releaseHost({ release: releaseBody("v1.1.0", "http://127.0.0.1:1/download/RPGVault.zip") })
  const second = await cli(vault, ["update", "--latest"], { RPGVAULT_RELEASE_API: gone.base })
  assert.notEqual(second.code, 0, `an undownloadable asset fails; stdout: ${second.stdout}`)
  assert.ok(second.stderr.includes("rpgvault: "), `the failure uses the CLI prefix: ${second.stderr}`)
  assert.equal(await installed(vault), "1.0.0", "the shipped layer is untouched")
  assert.deepEqual(await backups(vault), [], "no backup is written")
  assert.equal(await snapshot(vault), before, "the vault is unchanged and no half-written archive is kept")
  await gone.close()
  await cleanup(vault)
}, 60000)

test("--latest and --from are refused together, and --latest honours the fork in `_local/release.json`", async () => {
  const vault = await cloneVault("rpgvault-latest27-flags-")
  const served = await releaseHost({ asset: release("1.1.0") })
  const answer = await releaseHost({ release: releaseBody("v1.1.0", served.downloadUrl) })
  const both = await cli(vault, ["update", "--latest", "--from", repository], { RPGVAULT_RELEASE_API: answer.base })
  assert.notEqual(both.code, 0, `the two sources are refused together; stdout: ${both.stdout}`)
  assert.ok(both.stderr.includes("--from") && both.stderr.includes("--latest"), `the failure names both flags: ${both.stderr}`)
  assert.equal(await installed(vault), "1.0.0", "the refused run replaced nothing")
  await writeFile(path.join(vault, "_local/release.json"), JSON.stringify({ repo: "someone/Fork" }))
  const result = await cli(vault, ["update", "--latest"], { RPGVAULT_RELEASE_API: answer.base })
  assert.equal(result.code, 0, `the fork release installs; stdout: ${result.stdout}\nstderr: ${result.stderr}`)
  assert.ok(answer.requests.some(url => url.includes("/repos/someone/Fork/releases/latest")), `the fork is queried: ${answer.requests.join(", ")}`)
  assert.equal(await installed(vault), "1.1.0", "the fork release is installed")
  await served.close()
  await answer.close()
  await cleanup(vault)
}, 120000)

test("no secret from the vault reaches the output of an update", async () => {
  const vault = await cloneVault("rpgvault-latest27-secret-")
  await writeFile(path.join(vault, ".obsidian/plugins/table-tools/data.json"), JSON.stringify({ apiKey: "fake-key-012345" }))
  const served = await releaseHost({ asset: release("1.1.0") })
  const answer = await releaseHost({ release: releaseBody("v1.1.0", served.downloadUrl) })
  const result = await cli(vault, ["update", "--latest"], { RPGVAULT_RELEASE_API: answer.base })
  assert.equal(result.code, 0, `--latest succeeds; stderr: ${result.stderr}`)
  assert.equal(`${result.stdout}${result.stderr}`.includes("fake-key-012345"), false, "no plugin secret is printed")
  assert.equal(JSON.parse(await readFile(path.join(vault, ".obsidian/plugins/table-tools/data.json"), "utf8")).apiKey, "fake-key-012345", "the plugin data file is left alone")
  await served.close()
  await answer.close()
  await cleanup(vault)
}, 120000)

await run("acceptance 27 update latest")
